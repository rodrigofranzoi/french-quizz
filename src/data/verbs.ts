function er(
  infinitive: string,
  english: string,
  pp: string,
  fsStem: string,
  feminine?: { elle: string; elles: string },
): VerbEntry {
  return {
    infinitive,
    english,
    regular: true,
    auxiliary: 'avoir',
    present: buildPresentEr(infinitive),
    passeCompose: buildPasseComposeAvoir(pp, feminine),
    futurProche: buildFuturProche(infinitive),
    futurSimple: buildFuturSimple(fsStem),
  };
}

function etre(
  infinitive: string,
  english: string,
  pp: string,
  fsStem: string,
  feminine: { elle: string; elles: string },
  present: Record<Pronoun, string>,
  regular = false,
): VerbEntry {
  return {
    infinitive,
    english,
    regular,
    auxiliary: 'etre',
    present,
    passeCompose: buildPasseComposeEtre(pp, feminine),
    futurProche: buildFuturProche(infinitive),
    futurSimple: buildFuturSimple(fsStem),
    passeComposeFeminine: feminine,
  };
}

